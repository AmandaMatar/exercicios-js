// function declaration - formas comuns
function soma(x, y){
    return x + y
}

// function expression - formas comuns
const sub = function (x, y) {
    return x - y
}

console.log(sub(3, 4));

// named function expression - uso reduzido
const mult = function mult(x, y) {
    return x * y
}

console.log(mult(3, 4));
